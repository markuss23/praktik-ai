-- Description: Tabulka ai_usage, jeden řádek = jedno LLM volání (input/output tokeny).
--              Slouží k přehledu nákladů a k dennímu limitu tokenů pro roli user.
-- Requires existing tables: user
-- Idempotentní — lze spustit opakovaně.

CREATE TABLE IF NOT EXISTS ai_usage (
    usage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES "user"(user_id),
    endpoint VARCHAR(255),
    model VARCHAR(100) NOT NULL,
    input_tokens INTEGER NOT NULL,
    output_tokens INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_ai_usage_user_created ON ai_usage(user_id, created_at);
