-- Migration: 0038 - Log odeslaných e-mailů
-- Description: Záznam o každém pokusu o odeslání e-mailu (zobrazení historie na profilu, diagnostika SMTP).
-- Requires existing tables: "user", course
-- Idempotentní — lze spustit opakovaně, každý krok hlásí RAISE NOTICE.

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'email_status') THEN
    CREATE TYPE email_status AS ENUM ('sent', 'failed', 'skipped');
    RAISE NOTICE '[0038] Typ email_status vytvořen';
  ELSE
    RAISE NOTICE '[0038] Typ email_status už existuje — přeskočeno';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.tables WHERE table_name = 'email_log'
  ) THEN
    CREATE TABLE email_log (
      log_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id         BIGINT REFERENCES "user"(user_id) ON DELETE CASCADE,
      course_id       BIGINT REFERENCES course(course_id) ON DELETE SET NULL,
      event_key       VARCHAR(50)  NOT NULL,
      recipient_email VARCHAR(255) NOT NULL,
      subject         VARCHAR(255) NOT NULL,
      body            TEXT,
      status          email_status NOT NULL,
      error           TEXT,
      created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
    );
    RAISE NOTICE '[0038] Tabulka email_log vytvořena';
  ELSE
    RAISE NOTICE '[0038] Tabulka email_log už existuje — přeskočeno';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_indexes WHERE indexname = 'ix_email_log_user_created'
  ) THEN
    CREATE INDEX ix_email_log_user_created ON email_log (user_id, created_at);
    RAISE NOTICE '[0038] Index ix_email_log_user_created vytvořen';
  ELSE
    RAISE NOTICE '[0038] Index ix_email_log_user_created už existuje — přeskočeno';
  END IF;
END $$;
