-- Description: Tabulka vypnutých notifikací (existence řádku = uživatel má notifikaci vypnutou).
-- Requires existing tables: "user"
-- Idempotentní — lze spustit opakovaně.

CREATE TABLE IF NOT EXISTS notification_opt_out (
  opt_out_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
  event_key  VARCHAR(50) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_notification_opt_out_user_event
  ON notification_opt_out (user_id, event_key);
