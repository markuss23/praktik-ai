-- Migration: 0012 - Log odeslaných e-mailů
-- Description: Záznam o každém pokusu o odeslání e-mailu (zobrazení historie na profilu, diagnostika SMTP).
-- Requires existing tables: "user", course
-- Idempotentní — lze spustit opakovaně.

DO $$ BEGIN CREATE TYPE email_status AS ENUM ('sent', 'failed', 'skipped'); EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS email_log (
  log_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         BIGINT REFERENCES "user"(user_id) ON DELETE CASCADE,
  course_id       BIGINT REFERENCES course(course_id) ON DELETE SET NULL,
  event_key       VARCHAR(50)  NOT NULL,
  recipient_email VARCHAR(255) NOT NULL,
  subject         VARCHAR(255) NOT NULL,
  body            TEXT,
  status          email_status NOT NULL,
  error           TEXT,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_email_log_user_created
  ON email_log (user_id, created_at);
