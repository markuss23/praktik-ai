-- 1) Osy
CREATE TABLE IF NOT EXISTS ai_style_axis (
	axis_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
	code VARCHAR(10) NOT NULL,
	name VARCHAR(100) NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	is_active BOOLEAN NOT NULL,
	PRIMARY KEY (axis_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_ai_style_axis_code_active ON ai_style_axis (code) WHERE is_active;


-- 2) Nastavení na ose
CREATE TABLE IF NOT EXISTS ai_style_option (
	option_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
	axis_id BIGINT NOT NULL,
	code VARCHAR(20) NOT NULL,
	name VARCHAR(100) NOT NULL,
	description TEXT NOT NULL,
	example TEXT NOT NULL,
	is_default BOOLEAN NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	is_active BOOLEAN NOT NULL,
	PRIMARY KEY (option_id),
	FOREIGN KEY (axis_id) REFERENCES ai_style_axis (axis_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_ai_style_option_code_active ON ai_style_option (code) WHERE is_active;
CREATE UNIQUE INDEX IF NOT EXISTS uq_ai_style_option_default ON ai_style_option (axis_id) WHERE is_active AND is_default;


-- 3) Volba uživatele
CREATE TABLE IF NOT EXISTS user_ai_style (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
	user_id BIGINT NOT NULL,
	axis_id BIGINT NOT NULL,
	option_id BIGINT NOT NULL,
	created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
	PRIMARY KEY (id),
	FOREIGN KEY (user_id) REFERENCES "user" (user_id),
	FOREIGN KEY (axis_id) REFERENCES ai_style_axis (axis_id),
	FOREIGN KEY (option_id) REFERENCES ai_style_option (option_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_user_ai_style_user_axis ON user_ai_style (user_id, axis_id);


